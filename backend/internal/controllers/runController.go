// CreateRun handles the creation of a new run entry
func CreateRun(c *gin.Context) {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	var req models.CreateRunRequest
	var run models.Run

	// 1. Bind and Validate Request Body
	// Use ShouldBindJSON to bind the request body to the CreateRunRequest struct.
	// This also automatically performs validation based on the `binding` tags in the struct.
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid request data: " + err.Error()})
		return
	}

	// 2. Convert UserID string to ObjectID
	userID, err := bson.ObjectIDFromHex(req.UserID)
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid User ID format"})
		return
	}

	// 3. Prepare the Run model for insertion
	now := time.Now()
	run = models.Run{
		// ID will be generated by MongoDB
		UserID:    userID,
		Distance:  req.Distance,
		Date:      req.Date.UTC(), // Store date in UTC for consistency
		CreatedAt: now,
		UpdatedAt: now,
	}

	// 4. Insert into Database
	runsCollection := database.Runs() // Get the collection instance
	result, err := runsCollection.InsertOne(ctx, run)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Failed to create run entry: " + err.Error()})
		return
	}

	// 5. Respond with Success
	// Optionally fetch the created document or just return the ID
	run.ID = result.InsertedID.(bson.ObjectID) // Assign the generated ID back
	c.JSON(http.StatusCreated, run)            // Return the newly created run object
}

// GetRunHistogram handles fetching aggregated run data for histograms
func GetRunHistogram(c *gin.Context) {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	// 1. Get Query Parameters (UserID and Period)
	userIDStr := c.Query("userId")
	period := strings.ToLower(c.Query("period")) // day, week, month, year

	if userIDStr == "" {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Missing required query parameter: userId"})
		return
	}
	if period == "" {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Missing required query parameter: period"})
		return
	}

	// 2. Validate UserID
	userID, err := bson.ObjectIDFromHex(userIDStr)
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid User ID format"})
		return
	}

	// 3. Determine Grouping Format based on Period
	var groupFormat string
	switch period {
	case "day":
		groupFormat = "%Y-%m-%d" // Group by year-month-day
	case "week":
		// %U: Week of the year (Sunday as first day, 00-53)
		// %V: ISO 8601 week number (Monday as first day, 01-53)
		// %Y: Year for %U or %V
		groupFormat = "%Y-%V" // Group by year-week number (ISO standard)
	case "month":
		groupFormat = "%Y-%m" // Group by year-month
	case "year":
		groupFormat = "%Y" // Group by year
	default:
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid period. Allowed values: day, week, month, year"})
		return
	}

	// 4. Build Aggregation Pipeline
	// The pipeline will:
	// - $match: Filter runs for the specified user.
	// - $group: Group by the calculated period (_id) and sum the distances.
	// - $sort: Sort the results by the period for chronological order.
	// - $project: (Optional) Reshape the output if needed (already done by $group _id).
	pipeline := mongo.Pipeline{
		{ // Stage 1: Match documents for the specific user
			{Key: "$match", Value: bson.D{{Key: "userId", Value: userID}}},
		},
		{ // Stage 2: Group by the specified period and sum distances
			{Key: "$group", Value: bson.D{
				{Key: "_id", Value: bson.D{ // The grouping key
					{Key: "$dateToString", Value: bson.D{ // Convert date to string based on format
						{Key: "format", Value: groupFormat},
						{Key: "date", Value: "$date"},
						// Optionally add timezone here if needed, e.g., {Key: "timezone", Value: "UTC"}
					}},
				}},
				{Key: "totalDistance", Value: bson.D{ // Calculate the sum
					{Key: "$sum", Value: "$distance"},
				}},
			}},
		},
		{ // Stage 3: Sort by the period (_id)
			{Key: "$sort", Value: bson.D{{Key: "_id", Value: 1}}}, // 1 for ascending order
		},
	}

	// 5. Execute Aggregation
	runsCollection := database.Runs()
	cursor, err := runsCollection.Aggregate(ctx, pipeline)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Failed to aggregate run data: " + err.Error()})
		return
	}
	defer cursor.Close(ctx)

	// 6. Decode Results
	var results []models.HistogramDataPoint
	if err = cursor.All(ctx, &results); err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Failed to decode aggregation results: " + err.Error()})
		return
	}

	// Handle case where there might be no results (return empty array, not null)
	if results == nil {
		results = make([]models.HistogramDataPoint, 0)
	}

	// 7. Respond with Histogram Data
	c.JSON(http.StatusOK, results)
}
